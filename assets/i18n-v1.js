  function normalizeLanguage(value){
    return /^mn(?:[-_]|$)/i.test(String(value || "")) ? "mn" : "en";
  }

  function createI18n(initialLanguage){
    let language = normalizeLanguage(initialLanguage);
    return {
      get language(){ return language; },
      setLanguage(value){ language = normalizeLanguage(value); return language; },
      t(key, ...args){
        let value = STR[language]?.[key];
        if(value === undefined) value = STR.mn[key];
        if(typeof value === "function") return value(...args);
        return value === undefined ? key : value;
      }
    };
  }

  root.PushupI18n = Object.freeze({ STR, normalizeLanguage, createI18n });
